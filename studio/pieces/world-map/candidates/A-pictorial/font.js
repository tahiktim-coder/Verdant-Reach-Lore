// width of a text in px; track = px between letters
F.width = function (font, text, track) {
  let w = 0;
  for (const ch of text) { const g = font.glyphs[ch]; w += (g ? g[1].length : font.space) + track; }
  return w - track;
};
// call put(x, y) for every ink pixel of the text; (x, y) = top-left of the text box
F.plot = function (font, text, x, y, track, put) {
  for (const ch of text) {
    const g = font.glyphs[ch];
    if (!g) { x += font.space + track; continue; }
    for (let r = 1; r < g.length; r++) for (let k = 0; k < g[r].length; k++) if (g[r][k] === '#') put(x + k, y + g[0] + r - 1);
    x += g[1].length + track;
  }
};
