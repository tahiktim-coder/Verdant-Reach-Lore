const FONTS = { big: { glyphs: BIG, height: 7 }, small: { glyphs: SMALL, height: 8 } };
function measure(font, text, gap) {
  const G = FONTS[font].glyphs;
  let w = 0;
  for (const ch of text) { const g = G[ch]; if (g) w += g[0].length + gap; }
  return w - gap;
}
function draw(font, text, gap, plot, x, y) {
  const G = FONTS[font].glyphs;
  for (const ch of text) {
    const g = G[ch];
    if (!g) continue;
    for (let j = 0; j < g.length; j++) for (let i = 0; i < g[j].length; i++) if (g[j][i] === '#') plot(x + i, y + j);
    x += g[0].length + gap;
  }
}
const API = { FONTS, measure, draw };
